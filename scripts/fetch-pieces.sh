#!/usr/bin/env bash
# Downloads the freely licensed Lichess piece sets used by Grandie Chess into
# public/pieces/<set>/ and writes src/styles/pieces.css.
# Licences (from lichess-org/lila COPYING.md) are listed in CREDITS.md.
set -euo pipefail
ROOT="$(cd -- "$(dirname -- "$0")/.." && pwd)"
SETS=(cburnett merida chessnut fantasy spatial celtic rhosgfx mpchess)
BASE="https://raw.githubusercontent.com/lichess-org/lila/master/public/piece"
CSS="$ROOT/src/styles/pieces.css"
ROLES=(P:pawn N:knight B:bishop R:rook Q:queen K:king)

echo "/* Generated by scripts/fetch-pieces.sh: one scoped rule set per piece set. */" > "$CSS"
for set in "${SETS[@]}"; do
  dir="$ROOT/public/pieces/$set"
  mkdir -p "$dir"
  for color in w b; do
    for r in "${ROLES[@]}"; do
      letter="${r%%:*}"
      file="$dir/$color$letter.svg"
      [ -s "$file" ] || curl -fsSL -o "$file" "$BASE/$set/$color$letter.svg"
    done
  done
  for color in w b; do
    cname=$([ "$color" = w ] && echo white || echo black)
    for r in "${ROLES[@]}"; do
      letter="${r%%:*}"
      role="${r##*:}"
      echo ".pieces-$set .cg-wrap piece.$role.$cname { background-image: url('/pieces/$set/$color$letter.svg'); }" >> "$CSS"
    done
  done
  echo "fetched $set"
done
